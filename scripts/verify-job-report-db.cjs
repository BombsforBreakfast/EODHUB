// Isolated real Postgres execution; no credentials, network, or live email.
const {PGlite}=require(process.env.PGLITE_MODULE||'@electric-sql/pglite');
const {readFileSync}=require('node:fs');
const assert=require('node:assert/strict');
const {randomUUID}=require('node:crypto');
(async()=>{
 const db=new PGlite();let checks=0;
 const query=async(sql,args=[])=> (await db.query(sql,args)).rows;
 const one=async(sql,args=[])=> (await query(sql,args))[0];
 const check=(value,message)=>{assert.ok(value,message);checks++;};
 try {
 await db.exec(`create role anon;create role authenticated;create role service_role bypassrls;
 create table public.jobs(id uuid primary key default gen_random_uuid(),title text,company_name text,location text,pay_min numeric,pay_max numeric,description text,apply_url text,source_type text,is_approved boolean default false,is_rejected boolean default false);
 create table public.job_review_feedback(job_id uuid,decision text,created_at timestamptz default now());
 insert into jobs(title,is_approved) select 'Historical job '||n,true from generate_series(1,500) n;`);
 const pre=await one(`insert into jobs(title,is_approved,apply_url) values('Approved today before launch',true,'https://example.org/pre') returning id`);
 await db.query(`insert into job_review_feedback(job_id,decision) values($1,'approved')`,[pre.id]);
 await db.exec(readFileSync('supabase/migrations/20261111212242_job_report.sql','utf8'));
 await db.exec(readFileSync('supabase/migrations/20261111232629_job_report_checkout_retries.sql','utf8'));
 check((await one('select count(*)::int n from job_report_approvals')).n===0,'Historical inventory must not enter daily queue');
 const sub=await one(`select job_report_reserve(' TEST@example.org ',true) s`);const sid=sub.s.id;
 check(sub.s.email==='test@example.org','Email normalized and JSON result');
 await db.query("update job_report_subscribers set checkout_session_id='cs_open',checkout_started_at=now()-interval '1 hour' where id=$1",[sid]);
 check((await one("select job_report_reserve('test@example.org',true) s")).s.checkout_key===sub.s.checkout_key,'Preserve open checkout beyond forty minutes');
 const rotated=(await one("select job_report_reserve('test@example.org',true,true,$1) s",[sub.s.checkout_key])).s;
 check(rotated.checkout_key!==sub.s.checkout_key,'Expired checkout gets new attempt');
 check((await one("select job_report_reserve('test@example.org',true,true,$1) s",[sub.s.checkout_key])).s.checkout_key===rotated.checkout_key,'Concurrent expired-checkout retry reuses one attempt');
 const paid=new Date(Date.now()+30*86400000).toISOString();
 const sync=async(subscription,created,status='active',until=paid)=>one(`select job_report_sync($1,'cus_own',$2,$3,$4,$5,false,'test@example.org') s`,[sid,subscription,created,status,until]);
 await sync('sub_first',1);
 check((await one('select job_report_initial($1) result',[sid])).result,'First report queued');
 const initial=await one(`select payload from job_report_deliveries where kind='initial'`);
 check(initial.payload.jobs.length===1&&initial.payload.jobs[0].id===pre.id,'First report includes only actual approvals today, not 500 historical jobs');
 await one('select job_report_initial($1)',[sid]);
 check((await one('select count(*)::int n from job_report_deliveries')).n===2,'Repeated payment webhook cannot queue duplicate initial/welcome');
 const job=await one(`insert into jobs(title,is_approved,apply_url) values('Newly approved',true,'https://example.org/new') returning id`);
 await db.query('update jobs set is_approved=true where id=$1',[job.id]);
 check((await one('select count(*)::int n from job_report_approvals')).n===1,'Repeated approval does not duplicate');
 const rejected=await one(`insert into jobs(title,is_approved) values('Withdrawn',true) returning id`);
 await db.query('update jobs set is_approved=false,is_rejected=true where id=$1',[rejected.id]);
 await db.query(`update job_report_subscribers set subscribed_at=now()-interval '1 minute' where id=$1`,[sid]);
 const report=await one(`select job_report_prepare(now(),true) id`);
 const daily=await one(`select payload from job_report_deliveries where kind='report'`);
 check(daily.payload.jobs.length===1&&daily.payload.jobs[0].id===job.id,'Daily report excludes withdrawn jobs');
 check((await one(`select job_report_prepare(now(),true) id`)).id===report.id,'Repeated daily sweep reuses frozen report');
 check((await one(`select count(*)::int n from job_report_deliveries where kind='report'`)).n===1,'Daily report once per subscriber');
 await db.exec(readFileSync('supabase/migrations/20261113104828_job_report_manual_send.sql','utf8'));
 check((await one(`select job_report_prepare_manual(clock_timestamp(),true) id`)).id===null,'Empty manual send does not repeat morning report');
 const late=await one(`insert into jobs(title,is_approved,apply_url) values('Late approved job',true,'https://example.org/late') returning id`);
 check((await one(`select job_report_prepare_manual(clock_timestamp(),true) id`)).id===report.id,'Late batch belongs to today');
 const supplement=await one(`select payload from job_report_deliveries where message_key like 'report-late:%'`);
 check(supplement.payload.jobs.length===1&&supplement.payload.jobs[0].id===late.id,'Late send contains only unsent jobs');
 check((await one(`select job_report_prepare_manual(clock_timestamp(),true) id`)).id===null,'Repeated click sends no duplicate jobs');
 check((await one(`select jsonb_array_length(jobs) n from job_report_reports where id=$1`,[report.id])).n===1,'Original morning snapshot stays frozen');
 await db.query('delete from jobs where id=$1',[late.id]);
 check((await one(`select job_report_claim_one(id) claimed from job_report_deliveries where kind='report' order by created_at limit 1`)).claimed,'Can claim delivery');
 check(!(await one(`select job_report_claim_one(id) claimed from job_report_deliveries where kind='report' order by created_at limit 1`)).claimed,'Concurrent worker cannot claim leased delivery');
 await sync('sub_second',2);
 check((await one(`select count(*)::int n from job_report_deliveries where status='pending'`)).n===0,'Resubscription suppresses old pending mail');
 check((await sync('sub_first',1)).s.stripe_subscription_id==='sub_second','Stale subscription cannot overwrite new subscription');
 await assert.rejects(()=>one(`select job_report_sync($1,'cus_other','sub_bad',3,'active',$2,false,null)`,[sid,paid]));checks++;
 await one(`select job_report_request_manage('test@example.org',true,'hash','https://example.org/manage')`);
 check((await one(`select job_report_consume_manage('hash') id`)).id===sid,'Management token resolves correct subscriber');
 check((await one(`select job_report_consume_manage('hash') id`)).id===null,'Management token single use');
 await db.exec('set role anon');
 await assert.rejects(()=>query('select * from job_report_subscribers'));checks++;
 await assert.rejects(()=>query(`select job_report_reserve('thief@example.org',true)`));checks++;
 await db.exec('reset role;set role authenticated');
 await assert.rejects(()=>query('select * from job_report_manage_tokens'));checks++;
 await db.exec('reset role;set role service_role');
 check((await one('select count(*)::int n from job_report_subscribers')).n===1,'Service role can access newsletter tables');
 await db.exec('reset role');
 check((await one('select count(*)::int n from jobs')).n===503,'Existing job inventory retained');
 console.log(`Job Report database: ${checks} checks passed`);
 } finally {await db.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
